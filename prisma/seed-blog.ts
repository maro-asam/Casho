async function main() {
  console.log("🌱 Starting blog seed...\n");

  // Create categories
  console.log("📁 Creating categories...");
  const categoryMap: Record<string, string> = {};
  for (const cat of categories) {
    const created = await prisma.blogCategory.upsert({
      where: { slug: cat.slug },
      update: {},
      create: cat,
    });
    categoryMap[cat.slug] = created.id;
    console.log(`  ✓ ${cat.name}`);
  }

  // Create tags
  console.log("\n🏷️  Creating tags...");
  const tagMap: Record<string, string> = {};
  for (const tag of tags) {
    const created = await prisma.blogTag.upsert({
      where: { slug: tag.slug },
      update: {},
      create: tag,
    });
    tagMap[tag.slug] = created.id;
    console.log(`  ✓ ${tag.name}`);
  }

  // Create posts
  console.log("\n📝 Creating posts...");
  for (const post of posts) {
    const { categorySlug, tagSlugs, ...postData } = post;

    const existing = await prisma.blogPost.findUnique({
      where: { slug: postData.slug },
    });

    if (existing) {
      console.log(`  ⏭️  Skipped (exists): ${postData.title}`);
      continue;
    }

    await prisma.blogPost.create({
      data: {
        ...postData,
        status: "PUBLISHED",
        publishedAt: new Date(),
        categoryId: categorySlug ? categoryMap[categorySlug] : undefined,
        tags: {
          create: tagSlugs
            .filter((s) => tagMap[s])
            .map((s) => ({ tagId: tagMap[s] })),
        },
      },
    });
    console.log(`  ✓ ${postData.title}`);
  }

  console.log("\n✅ Blog seed completed successfully!");
}

main()
  .catch((e) => {
    console.error("❌ Seed failed:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
