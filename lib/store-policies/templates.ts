// Ready-made Arabic policy texts, filled with the store's details.
//
// Written to be true for a typical Casho store and in line with Egypt's
// Consumer Protection Law (181/2018: 14 days to return or exchange in original
// condition, a longer window for defective goods) and Personal Data Protection
// Law (151/2020). They are a starting point — the merchant reviews and edits
// them from the dashboard. Keep every claim generic enough to hold for any
// store; anything store-specific comes from the context below.
//
// Format: see parsePolicy in ./index.ts ("#" headings, "-" bullets).

import type { PolicyType } from "./index";

export type PolicyTemplateContext = {
  storeName: string;
  email: string | null;
  whatsapp: string | null;
  /** The store sells downloadable products. */
  hasDigital: boolean;
  /** Ad platforms whose pixel runs on the store (e.g. "Meta", "TikTok"). */
  adPlatforms: string[];
};

const join = (lines: (string | false | null | undefined)[]) =>
  lines.filter((line): line is string => typeof line === "string").join("\n");

function contactSection(ctx: PolicyTemplateContext) {
  const email = ctx.email?.trim();
  const whatsapp = ctx.whatsapp?.trim();
  const line =
    whatsapp && email
      ? `لأي استفسار، تواصل معنا على واتساب ${whatsapp} أو على البريد الإلكتروني ${email}.`
      : whatsapp
        ? `لأي استفسار، تواصل معنا على واتساب ${whatsapp}.`
        : email
          ? `لأي استفسار، تواصل معنا على البريد الإلكتروني ${email}.`
          : `لأي استفسار، تواصل معنا من صفحة "تواصل معنا" في المتجر.`;
  return join(["", "# تواصل معنا", line]);
}

function contactShort(ctx: PolicyTemplateContext) {
  if (ctx.whatsapp?.trim() && ctx.email?.trim()) return "على واتساب أو البريد الإلكتروني";
  if (ctx.whatsapp?.trim()) return "على واتساب";
  if (ctx.email?.trim()) return "على البريد الإلكتروني";
  return `من صفحة "تواصل معنا"`;
}

function listAnd(items: string[]) {
  if (items.length <= 1) return items.join("");
  return `${items.slice(0, -1).join(" و")} و${items[items.length - 1]}`;
}

