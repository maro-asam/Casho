const TEMPLATES: Record<PolicyType, (ctx: PolicyTemplateContext) => string> = {
  returns: returnsTemplate,
  shipping: shippingTemplate,
  privacy: privacyTemplate,
  terms: termsTemplate,
};

export function buildPolicyTemplate(type: PolicyType, ctx: PolicyTemplateContext): string {
  return TEMPLATES[type]({ ...ctx, storeName: ctx.storeName.trim() || "متجرنا" });
}
