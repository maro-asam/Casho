// Generates app/(welcome)/_components/apple/world-dots.ts: a 1° land mask of
// the world for the landing hero's dotted map.
//
// The outlines come from svg-dotted-map (simplified Natural Earth countries,
// MIT). The package doesn't export them, so this reads the object literal out
// of its bundle. Run: node scripts/gen-world-dots.mjs

import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("node_modules/svg-dotted-map/dist/index.mjs", "utf8");
const start = src.indexOf("var L=") + "var L=".length;
const end = src.indexOf(";var J=", start);
if (start < 6 || end < 0) throw new Error("svg-dotted-map bundle layout changed");
const world = new Function(`return ${src.slice(start, end)}`)();

const LAT0 = 75; // first row
const ROWS = 132; // 75°N → 56°S
const COLS = 360;

const polys = world.features.flatMap((f) => {
  const g = f.geometry;
  const list = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  return list.map((rings) => {
    const outer = rings[0];
    const xs = outer.map((p) => p[0]);
    const ys = outer.map((p) => p[1]);
    return {
      id: f.id,
      rings,
      box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)],
    };
  });
});

function inRing(x, y, ring) {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

function countryAt(x, y) {
  for (const p of polys) {
    const [x0, y0, x1, y1] = p.box;
    if (x < x0 || x > x1 || y < y0 || y > y1) continue;
    if (!inRing(x, y, p.rings[0])) continue;
    if (p.rings.slice(1).some((hole) => inRing(x, y, hole))) continue;
    return p.id;
  }
  return null;
}

const bytes = new Uint8Array(Math.ceil((ROWS * COLS) / 8));
const egypt = [];
let land = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = LAT0 - r;
  for (let c = 0; c < COLS; c++) {
    // Odd rows sit half a step over, for a staggered grid.
    const lon = -180 + c + (r % 2 ? 0.5 : 0) + 0.25;
    const id = countryAt(lon, lat);
    if (!id) continue;
    const i = r * COLS + c;
    bytes[i >> 3] |= 1 << (i & 7);
    land++;
    if (id === "EGY") egypt.push(i);
  }
}

const out = `// Generated by scripts/gen-world-dots.mjs — do not edit by hand.
// Land at 1° on a staggered grid: row r is latitude ${LAT0} - r, column c is
// longitude -180 + c (+0.5 on odd rows). Bit (r * ${COLS} + c) is set on land.
// Outlines: svg-dotted-map (simplified Natural Earth, MIT).

export const WORLD = {
  lat0: ${LAT0},
  rows: ${ROWS},
  cols: ${COLS},
  bits: "${Buffer.from(bytes).toString("base64")}",
} as const;

/** Cells inside Egypt, lit as home. */
export const EGYPT_CELLS: readonly number[] = [${egypt.join(",")}];
`;
writeFileSync("app/(welcome)/_components/apple/world-dots.ts", out);
console.log(`land cells: ${land}, egypt: ${egypt.length}, bytes: ${out.length}`);
