// Regenerates lib/i18n/dashboard/en/index.ts from the JSON parts in that folder.
import fs from "node:fs";
import path from "node:path";

const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../../lib/i18n/dashboard/en");
const parts = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const ident = (f) => "_" + f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");

// Report the same key translated differently in two parts.
const seen = new Map();
for (const f of parts) {
  for (const [k, v] of Object.entries(JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")))) {
    const prev = seen.get(k);
    if (prev && prev.v !== v) console.warn(`conflict: ${JSON.stringify(k)} — ${prev.f}: ${JSON.stringify(prev.v)} vs ${f}: ${JSON.stringify(v)}`);
    if (!/\{\d+\}/.test(k) && /\{\d+\}/.test(v)) console.warn(`placeholder added in ${f}: ${JSON.stringify(k)}`);
    for (const m of k.match(/\{\d+\}/g) ?? []) if (!v.includes(m) && !(k.includes("{3}") && m === "{3}")) console.warn(`placeholder ${m} dropped in ${f}: ${JSON.stringify(k)}`);
    seen.set(k, { f, v });
  }
}

const src = `// Generated by scripts/i18n/build-en-index.mjs — do not edit by hand.
// Arabic source text → English, split by dashboard area.
import type { Dictionary } from "../runtime";
${parts.map((f) => `import ${ident(f)} from "./${f}";`).join("\n")}

const english: Dictionary = Object.assign({}, ${parts.map(ident).join(", ")});
export default english;
`;
fs.writeFileSync(path.join(dir, "index.ts"), src);
console.log(`${parts.length} parts, ${seen.size} keys`);
